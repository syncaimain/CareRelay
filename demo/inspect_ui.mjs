import { chromium, expect } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';

const browser = await chromium.launch();
const context = await browser.newContext({viewport:{width:1440,height:1000}});
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await mkdir('demo/assets/screenshots', {recursive:true});
await page.goto(process.env.PLAYWRIGHT_BASE_URL || 'http://127.0.0.1:3104');
await page.waitForLoadState('networkidle');
await expect(page.getByRole('button',{name:'Create fictional care circle'})).toBeVisible();
await page.screenshot({path:'demo/assets/screenshots/00-welcome.png',fullPage:true});
await page.getByRole('button',{name:'Create fictional care circle'}).click();
await expect(page.getByRole('heading',{name:'Good to see you, Alex.'})).toBeVisible();
await page.screenshot({path:'demo/assets/screenshots/01-overview.png',fullPage:true});
await page.getByRole('button',{name:'Import messages',exact:true}).click();
await page.getByRole('button',{name:'Load fictional conversation'}).click();
await expect(page.getByLabel('Messages and notes')).toContainText('Oak Clinic');
await page.screenshot({path:'demo/assets/screenshots/02-source.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'demo/assets/screenshots/mobile-import.png',fullPage:true});
const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
await page.getByRole('button',{name:'Toggle navigation'}).click();
await page.getByRole('button',{name:'Overview',exact:true}).click();
await page.screenshot({path:'demo/assets/screenshots/mobile-overview.png',fullPage:true});
await writeFile('docs/ui-inspection.json',JSON.stringify({viewport:{width:1440,height:1000},mobile:{width:390,height:844},horizontalOverflow:overflow,pageErrors:errors},null,2));
await browser.close();
console.log(JSON.stringify({horizontalOverflow:overflow,pageErrors:errors}));
if(overflow || errors.length) process.exitCode=1;
